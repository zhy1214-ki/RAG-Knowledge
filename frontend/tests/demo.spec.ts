import { test, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'

test('register, create KB, upload Word, ask with sources, history and delete', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', err => errors.push(err.message))
  const stamp = Date.now().toString()
  await page.goto('/login')
  await page.getByText('还没有账号？创建账号').click()
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill('browser_' + stamp)
  await page.getByRole('textbox', { name: '密码', exact: true }).fill('Browser-test-123')
  await page.getByRole('button', { name: '注册并进入' }).click()
  await expect(page.getByRole('heading', { name: /你好/ })).toBeVisible()
  await page.getByRole('link', { name: '知识库管理' }).click()
  await page.getByRole('button', { name: '创建知识库' }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('input').fill('浏览器验收_' + stamp)
  await dialog.locator('textarea').fill('本项目合成演示文档')
  await dialog.getByRole('button', { name: '保存' }).click()
  await expect(page.getByRole('heading', { name: '浏览器验收_' + stamp, exact: true })).toBeVisible()
  await page.getByRole('button', { name: '文档', exact: true }).click()
  await expect(page.getByRole('button', { name: '上传文档', exact: true })).toBeEnabled()
  await page.locator('input[type=file]').setInputFiles(fileURLToPath(new URL('../../samples/travel-policy.docx', import.meta.url)))
  await expect(page.locator('.document-table').getByText('已索引', { exact: true })).toBeVisible({ timeout: 60000 })
  await page.screenshot({ path: fileURLToPath(new URL('../../docs/screenshots/documents.png', import.meta.url)), fullPage: true })
  await page.getByRole('link', { name: 'AI 智能问答' }).click()
  await page.getByRole('textbox', { name: '问题' }).fill('差旅报销需要多久提交？')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.chat-message.assistant')).toContainText('三十天', { timeout: 30000 })
  await expect(page.locator('.chat-message.assistant')).toContainText('travel-policy.docx')
  await page.locator('.el-collapse-item__header').first().click()
  await expect(page.getByText(/文档 ID：/)).toBeVisible()
  await page.screenshot({ path: fileURLToPath(new URL('../../docs/screenshots/chat.png', import.meta.url)), fullPage: true })
  await page.getByRole('link', { name: '会话历史' }).click()
  await expect(page.locator('.history-entry').filter({ hasText: '差旅报销需要多久提交？' })).toBeVisible()
  await page.getByRole('button', { name: '继续问答' }).click()
  await expect(page.locator('.chat-message.assistant')).toContainText('三十天')
  await page.getByRole('link', { name: '文档管理' }).click()
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByText('还没有文档，上传一份开始吧')).toBeVisible()
  await page.getByRole('link', { name: '知识库管理' }).click()
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByText('创建第一个知识库，开始整理知识')).toBeVisible()
  expect(errors).toEqual([])
})
